// src/app/api/core-setup/action-items/[key]/[decision]/route.ts
//
// POST /api/core-setup/action-items/:key/approve|reject|modify?companyId=...
//
// Records the decision on an Action Center item (ADMIN, SUPER_ADMIN and HR). On approval the front end applies the proposed
// changes itself through the normal record endpoints (sending X-Change-Source: action_center, so those changes are logged as
// coming from an approval) and then reports here how many it applied. The decision and its audit row are one transaction.
import { NextRequest } from 'next/server'
import { prisma } from '@/app/lib/db'
import { requireRole } from '@/app/lib/auth'
import { ApiResponse, handleApiError } from '@/app/lib/utils'
import { handleCorsOptions, withCors } from '@/app/lib/cors'
import { AUTOMATION_DECIDER_ROLES, companyForRequest } from '@/app/lib/core-setup/automation'
import { actorFor, recordCoreSetupEvent } from '@/app/lib/core-setup/audit'

export async function OPTIONS(request: NextRequest) {
  return handleCorsOptions(request)
}

const VERB: Record<string, string> = { approve: 'Approved', reject: 'Rejected', modify: 'Modified' }
const CHANGE_TYPE: Record<string, string> = { approve: 'approved', reject: 'rejected', modify: 'modified' }

interface ChangeInput {
  label?: unknown
  from?: unknown
  to?: unknown
}

export async function POST(request: NextRequest, { params }: { params: { key: string; decision: string } }) {
  const origin = request.headers.get('origin')
  try {
    const authHeader = request.headers.get('authorization')
    if (!authHeader) {
      return withCors(ApiResponse.error('Authorization header missing', 401), origin)
    }
    const user = requireRole(authHeader.replace('Bearer ', ''), AUTOMATION_DECIDER_ROLES)

    const { key: rawKey, decision } = params
    if (!VERB[decision]) {
      return withCors(ApiResponse.error('decision must be approve, reject or modify', 400), origin)
    }
    const itemKey = decodeURIComponent(rawKey)

    const scope = await companyForRequest(request, user)
    if ('error' in scope) {
      return withCors(ApiResponse.error(scope.error, scope.status), origin)
    }
    const { companyId } = scope

    const body = (await request.json().catch(() => ({}))) as Record<string, unknown>
    const changes = (Array.isArray(body.changes) ? body.changes : []) as ChangeInput[]
    const failed = Array.isArray(body.failed) ? body.failed : []
    const title = String(body.title || itemKey)
    const ruleId = body.ruleId ? String(body.ruleId) : null
    const reason = body.reason ? String(body.reason) : ''
    const value = body.value ? String(body.value) : ''
    const verb = VERB[decision]
    const actor = await actorFor(user)

    const saved = await prisma.$transaction(async (tx) => {
      const data = {
        decision,
        reason: reason || null,
        applied: changes.length,
        value: value || null,
        signature: body.signature ? String(body.signature) : null,
        title,
        ruleId,
        decidedById: actor.userId ?? null,
        decidedByName: actor.name,
        decidedByRole: user.role,
        decidedAt: new Date(),
      }
      const row = await tx.actionItemDecision.upsert({
        where: { companyId_itemKey: { companyId, itemKey } },
        update: data,
        create: { companyId, itemKey, ...data },
      })

      await recordCoreSetupEvent(tx, {
        companyId,
        actor,
        kind: 'decision',
        action: `${changes.length ? 'Approved and applied' : verb}: ${title}`,
        object: title,
        changeType: CHANGE_TYPE[decision],
        status: CHANGE_TYPE[decision],
        reason,
        summary: changes.length
          ? `Approved "${title}" and applied ${changes.length} change${changes.length === 1 ? '' : 's'}${failed.length ? `. ${failed.length} could not be changed.` : '.'}`
          : `${verb} the recommendation "${title}".`,
        fieldChanges: changes.map((c) => ({ field: String(c.label ?? ''), previousValue: String(c.from ?? ''), newValue: String(c.to ?? ''), changeType: 'changed' })),
        details: [
          { label: 'Decision', value: verb },
          ...(value ? [{ label: 'Proposed value', value }] : []),
          ...(reason ? [{ label: 'Reason', value: reason }] : []),
        ],
        related: ruleId ? [{ type: 'automation_rule', name: ruleId, identifier: ruleId, status: 'Enabled', relationship: 'Generated by' }] : [],
      })
      return row
    })

    return withCors(
      ApiResponse.success(
        {
          decision: saved.decision,
          reason: saved.reason ?? '',
          applied: saved.applied,
          value: saved.value ?? '',
          signature: saved.signature ?? '',
          title: saved.title ?? itemKey,
          ruleId: saved.ruleId,
          by: saved.decidedByName ?? '',
          role: saved.decidedByRole ?? '',
          at: saved.decidedAt.toISOString(),
        },
        verb,
      ),
      origin,
    )
  } catch (error) {
    return withCors(handleApiError(error), origin)
  }
}
