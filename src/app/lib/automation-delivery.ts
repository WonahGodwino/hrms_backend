import {
  AutomationAudience,
  AutomationChannel,
  Prisma,
} from "@prisma/client";
import prisma from "@/app/lib/prisma";
import { createNotification } from "@/app/lib/notifications/helpers";
import { sendEmail } from "@/app/lib/email";

export type AutomationRecipient = {
  id: string; // StaffRecord.id
  email?: string | null;
  name?: string | null;
};

export type DeliveryItemResult = {
  recipientId: string;
  channel: AutomationChannel;
  status: "SENT" | "FAILED" | "SKIPPED";
  note?: string;
};

export type AudienceDeliveryResolution = {
  allowed: boolean;
  channel: AutomationChannel;
  reason?: string;
};

/**
 * Template gating (Section 8):
 * For SEND_REMINDER the audience is REVIEWING_MANAGERS when the recipient is a manager, otherwise ALL_EMPLOYEES;
 * for NOTIFY_HR and the HR notice of ESCALATE_APPROVAL it is HR_ADMINS.
 * Look at AutomationNotification rows (not removed) for that audience:
 * - If some are enabled, use the oldest enabled one's channel;
 * - If templates exist but all are paused, suppress delivery (reason: "notification templates for {audience} are paused");
 * - If no template exists for that audience, use EMAIL_APP.
 */
export async function resolveAudienceDelivery(
  companyId: string,
  audience: AutomationAudience,
): Promise<AudienceDeliveryResolution> {
  const templates = await prisma.automationNotification.findMany({
    where: { companyId, removedAt: null, audience },
    orderBy: { createdAt: "asc" },
    select: { id: true, enabled: true, channel: true },
  });

  if (templates.length === 0) {
    return {
      allowed: true,
      channel: "EMAIL_APP",
    };
  }

  const enabled = templates.filter((t) => t.enabled);
  if (enabled.length > 0) {
    return {
      allowed: true,
      channel: enabled[0].channel,
    };
  }

  return {
    allowed: false,
    channel: "EMAIL_APP",
    reason: `notification templates for ${audience} are paused`,
  };
}

/**
 * Deliver an automation message across in-app and/or email channels.
 * Maps AutomationChannel:
 * - EMAIL_APP: in-app notification + email
 * - EMAIL: email only
 * - APP: in-app notification only
 * - SMS: falls back to EMAIL_APP when no SMS provider exists, with a note in result.delivery
 */
export async function deliverAutomationMessage(params: {
  companyId: string;
  recipients: AutomationRecipient[];
  subject: string;
  body: string;
  channel: AutomationChannel;
}): Promise<DeliveryItemResult[]> {
  const { companyId, recipients, subject, body, channel } = params;
  const results: DeliveryItemResult[] = [];

  const effectiveChannel = channel;
  const isSmsFallback = channel === "SMS";

  const deliverInApp =
    effectiveChannel === "EMAIL_APP" ||
    effectiveChannel === "APP" ||
    isSmsFallback;
  const deliverEmail =
    effectiveChannel === "EMAIL_APP" ||
    effectiveChannel === "EMAIL" ||
    isSmsFallback;

  for (const recipient of recipients) {
    let inAppOk = false;
    let emailOk = false;
    const notes: string[] = [];

    if (isSmsFallback) {
      notes.push("SMS provider not configured; fell back to in-app & email");
    }

    if (deliverInApp) {
      try {
        const notif = await createNotification(
          recipient.id,
          "AUTOMATION_RULE_ACTION",
          subject,
          body,
          { source: "RULES_ENGINE", companyId },
          companyId,
        );
        if (notif) {
          inAppOk = true;
        } else {
          notes.push("in-app notification returned null");
        }
      } catch (err) {
        notes.push(
          `in-app failed: ${err instanceof Error ? err.message : String(err)}`,
        );
      }
    }

    if (deliverEmail) {
      if (recipient.email) {
        try {
          const emailResult = await sendEmail({
            to: recipient.email,
            subject,
            text: body,
            html: `<div style="font-family: sans-serif; line-height: 1.5; color: #1e293b;">
              <h2 style="color: #0f172a; margin-bottom: 16px;">${escapeHtml(subject)}</h2>
              <div style="white-space: pre-wrap; margin-bottom: 24px;">${escapeHtml(body)}</div>
              <hr style="border: 0; border-top: 1px solid #e2e8f0; margin: 24px 0;" />
              <p style="font-size: 12px; color: #64748b;">This automated notification was generated by 247HR Rules Engine.</p>
            </div>`,
          });
          if (emailResult.success) {
            emailOk = true;
          } else {
            notes.push(`email error: ${emailResult.error || "unknown"}`);
          }
        } catch (err) {
          notes.push(
            `email failed: ${err instanceof Error ? err.message : String(err)}`,
          );
        }
      } else {
        notes.push("no email address on staff record");
      }
    }

    const succeeded =
      effectiveChannel === "APP"
        ? inAppOk
        : effectiveChannel === "EMAIL"
          ? emailOk
          : inAppOk || emailOk;

    results.push({
      recipientId: recipient.id,
      channel,
      status: succeeded ? "SENT" : "FAILED",
      note: notes.length ? notes.join("; ") : undefined,
    });
  }

  return results;
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
