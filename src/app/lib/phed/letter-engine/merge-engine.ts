// ============================================================
// Pure merge engine — (rows, runInputs, template) → findings + render models.
// No network, disk or database access. Validation, preview and PDF generation
// all call this so they never disagree.
// ============================================================

import type {
  EngineResult, Finding, LetterRow, RenderModel, RowResult, RunInputs, TemplateConfig,
} from './types'
import { validateRunInputs, validateRowValues } from './validators'
import { formatNgn } from './currency-formatter'
import { formatDateLong, parseDate } from './date-formatter'
import { TOKEN_PATTERN } from './token-map'

function hasError(findings: Finding[]): boolean {
  return findings.some((f) => f.severity === 'ERROR')
}

export function validateAndRender(
  rows: LetterRow[],
  runInputs: RunInputs,
  template: TemplateConfig,
): EngineResult {
  const fatal = validateRunInputs(runInputs)
  const canRender = fatal.length === 0

  // ── V-06 duplicate Employee ID (cross-row) ─────────────────────
  const byId = new Map<string, LetterRow[]>()
  for (const row of rows) {
    const key = row.employeeId.trim().toLowerCase()
    if (!key) continue
    const list = byId.get(key) ?? []
    list.push(row)
    byId.set(key, list)
  }

  const rowResults: RowResult[] = rows.map((row) => {
    const rowValidation = validateRowValues(row)
    const findings = [...rowValidation.findings]

    const key = row.employeeId.trim().toLowerCase()
    if (key && (byId.get(key)?.length ?? 0) > 1) {
      findings.push({
        code: 'V-06',
        severity: 'ERROR',
        row: row.excelRow,
        column: 'Employee ID',
        message: `Employee ID "${row.employeeId.trim()}" appears on more than one row.`,
      })
    }

    const excluded = hasError(findings)
    let renderModel: RenderModel | null = null

    if (
      canRender &&
      !excluded &&
      rowValidation.previousGross !== null &&
      rowValidation.currentGross !== null &&
      rowValidation.previousWords !== null &&
      rowValidation.currentWords !== null
    ) {
      renderModel = buildRenderModel(
        row, runInputs, template,
        rowValidation.previousGross, rowValidation.currentGross,
        rowValidation.previousWords, rowValidation.currentWords,
      )
    }

    return {
      excelRow: row.excelRow,
      employeeId: row.employeeId.trim(),
      findings,
      renderModel,
      wordsAutoGenerated: rowValidation.wordsAutoGenerated,
    }
  })

  const valid = rowResults.filter((r) => r.renderModel !== null).length
  const warnings = rowResults.reduce(
    (sum, r) => sum + r.findings.filter((f) => f.severity === 'WARNING').length,
    0,
  )

  return {
    fatal,
    rows: rowResults,
    counts: { total: rows.length, valid, excluded: rows.length - valid, warnings },
  }
}

function buildRenderModel(
  row: LetterRow,
  runInputs: RunInputs,
  template: TemplateConfig,
  previousGross: number,
  currentGross: number,
  previousWords: string,
  currentWords: string,
): RenderModel {
  const ov = row.overrides
  const letterDate = parseDate(ov.letterDate ?? runInputs.letterDate)!
  const effectiveDate = parseDate(ov.effectiveDate ?? runInputs.effectiveDate)!

  return {
    letter_date: formatDateLong(letterDate),
    staff_name: row.name.trim(),
    staff_id: row.employeeId.trim(),
    first_name: row.firstName.trim(),
    approval_period: (ov.approvalPeriod ?? runInputs.approvalPeriod).trim(),
    previous_gross: formatNgn(previousGross),
    previous_gross_words: previousWords,
    current_gross: formatNgn(currentGross),
    current_gross_words: currentWords,
    effective_date: formatDateLong(effectiveDate),
    performance_year: (ov.performanceYear ?? runInputs.performanceYear).trim(),
    signatory_name: template.signatoryName,
    signatory_title: template.signatoryTitle,
  }
}

/**
 * Merge a render model into a template body. Every {{token}} is replaced;
 * a token with no value is left as-is so the caller can treat it as a leak.
 * Inserted values are plain text — they are never re-scanned for tokens.
 */
export function renderLetterText(renderModel: RenderModel, body: string): string {
  return body.replace(TOKEN_PATTERN, (_match, name: string) => {
    const value = (renderModel as unknown as Record<string, string>)[name]
    return value === undefined || value === null ? `{{${name}}}` : value
  })
}

/** True when any unresolved {{token}} remains in the rendered text (template leak). */
export function hasUnresolvedTokens(text: string): boolean {
  TOKEN_PATTERN.lastIndex = 0
  return TOKEN_PATTERN.test(text)
}
