// ============================================================
// Bulk Staff Promotion Letter — engine types (pure, no I/O)
// ============================================================

export type LetterType = 'SALARY_INCREASE'

export type FindingSeverity = 'FATAL' | 'ERROR' | 'WARNING'

export interface Finding {
  code: string            // V-01 … V-14
  severity: FindingSeverity
  row?: number            // 1-based Excel row (only for row-level findings)
  column?: string         // canonical column header (only for row-level findings)
  message: string
}

/** One normalised staff row after header matching (raw cell text). */
export interface LetterRow {
  excelRow: number
  employeeId: string
  firstName: string
  name: string
  initialGrossPay: string
  previousAnnualGross: string
  currentAnnualGross: string
  previousAmountInWords: string
  currentAmountInWords: string
  annualRemuneration: string
  mail: string
  /** Optional per-row overrides (fall back to run inputs when absent). */
  overrides: {
    letterDate?: string
    effectiveDate?: string
    performanceYear?: string
    approvalPeriod?: string
  }
}

/** Parsed/derived row values produced by the validators. */
export interface ParsedRow {
  previousGross: number
  currentGross: number
  annualRemuneration: number | null
  previousWords: string
  currentWords: string
  wordsAutoGenerated: { previous: boolean; current: boolean }
}

export interface RunInputs {
  letterDate: string
  effectiveDate: string
  performanceYear: string
  approvalPeriod: string
}

export interface TemplateConfig {
  type: LetterType
  version: number
  body: string            // canonical text containing {{tokens}}
  letterhead: string      // address block + "Personal and Confidential"
  signatoryName: string
  signatoryTitle: string
  tokens: string[]
}

/** Resolved values for the 13 tokens of one row (plain text). */
export interface RenderModel {
  letter_date: string
  staff_name: string
  staff_id: string
  first_name: string
  approval_period: string
  previous_gross: string
  previous_gross_words: string
  current_gross: string
  current_gross_words: string
  effective_date: string
  performance_year: string
  signatory_name: string
  signatory_title: string
}

export interface RowResult {
  excelRow: number
  employeeId: string
  findings: Finding[]
  /** null when the row is excluded (any ERROR finding). */
  renderModel: RenderModel | null
  /** which salary words were auto-generated (empty words cell). */
  wordsAutoGenerated: { previous: boolean; current: boolean }
}

export interface EngineResult {
  fatal: Finding[]
  rows: RowResult[]
  counts: {
    total: number
    valid: number
    excluded: number
    warnings: number
  }
}
