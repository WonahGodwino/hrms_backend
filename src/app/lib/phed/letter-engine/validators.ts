// ============================================================
// Validation rules V-05 … V-14 (pure). V-01 … V-04 are handled in the
// intake route because they need the raw workbook/file.
// ============================================================

import type { Finding, LetterRow, RunInputs } from './types'
import { parseSalary } from './currency-formatter'
import { isValidPerformanceYear, parseDate, daysBetween } from './date-formatter'
import { nairaToWords, amountWordsEqual } from './words-converter'

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/
const PLACEHOLDER_RE = /(\.{2,}|…|n\/a|nil|none)/i

function err(code: string, row: number, column: string, message: string): Finding {
  return { code, severity: 'ERROR', row, column, message }
}
function warn(code: string, row: number, column: string, message: string): Finding {
  return { code, severity: 'WARNING', row, column, message }
}

function hasLetter(s: string): boolean {
  return /[a-zA-Z]/.test(s)
}

function isAllCaps(s: string): boolean {
  return hasLetter(s) && s === s.toUpperCase()
}

/**
 * V-14 — validate the four run-level inputs.
 * Malformed dates / non-4-digit year → FATAL. Effective Date outside
 * [today-12m, today+12m] → WARNING.
 */
export function validateRunInputs(runInputs: RunInputs, now: Date = new Date()): Finding[] {
  const findings: Finding[] = []

  const letterDate = parseDate(runInputs.letterDate)
  if (!letterDate) findings.push({ code: 'V-14', severity: 'FATAL', column: 'Letter Date', message: 'Letter Date must be a real date (e.g. 2 October 2026).' })

  const effectiveDate = parseDate(runInputs.effectiveDate)
  if (!effectiveDate) {
    findings.push({ code: 'V-14', severity: 'FATAL', column: 'Effective Date', message: 'Effective Date must be a real date (e.g. 1 January 2027).' })
  } else {
    const days = daysBetween(now, effectiveDate)
    if (days < -365 || days > 365) {
      findings.push({ code: 'V-14', severity: 'WARNING', column: 'Effective Date', message: 'Effective Date is more than 12 months from today — confirm it is intended.' })
    }
  }

  if (!isValidPerformanceYear(runInputs.performanceYear)) {
    findings.push({ code: 'V-14', severity: 'FATAL', column: 'Performance Year', message: 'Performance Year must be a four-digit year (e.g. 2025).' })
  }

  if (!runInputs.approvalPeriod || !runInputs.approvalPeriod.trim()) {
    findings.push({ code: 'V-14', severity: 'FATAL', column: 'Approval Period', message: 'Approval Period is required (free text, e.g. 2026).' })
  }

  return findings
}

export interface RowValidation {
  findings: Finding[]
  /** Parsed values; null when a required salary cell is missing/invalid. */
  previousGross: number | null
  currentGross: number | null
  annualRemuneration: number | null
  previousWords: string | null
  currentWords: string | null
  wordsAutoGenerated: { previous: boolean; current: boolean }
}

/**
 * Apply the per-row rules (V-05, V-07 … V-13) to one row.
 * V-06 (duplicate Employee ID) is handled cross-row by the merge engine.
 */
export function validateRowValues(row: LetterRow): RowValidation {
  const findings: Finding[] = []
  const wordsAutoGenerated = { previous: false, current: false }

  // ── V-05 — Employee ID (required, text) ──────────────────────
  if (!row.employeeId.trim()) {
    findings.push(err('V-05', row.excelRow, 'Employee ID', 'Employee ID is required.'))
  }

  // ── V-05 / V-12 / V-13 — names ────────────────────────────────
  for (const [col, value] of [['First Name', row.firstName], ['Name', row.name]] as const) {
    if (!value.trim()) {
      findings.push(err('V-05', row.excelRow, col, `${col} is required.`))
      continue
    }
    if (value.length > 100) {
      findings.push(err('V-12', row.excelRow, col, `${col} is longer than 100 characters.`))
    }
    if (PLACEHOLDER_RE.test(value)) {
      findings.push(err('V-12', row.excelRow, col, `${col} contains placeholder text (${value}).`))
    }
    if (!hasLetter(value)) {
      findings.push(err('V-12', row.excelRow, col, `${col} must contain at least one letter.`))
    }
    if (isAllCaps(value)) {
      findings.push(warn('V-13', row.excelRow, col, `${col} is written in ALL CAPITALS — confirm the casing is correct.`))
    }
  }

  // ── V-05 / V-07 — salary cells ────────────────────────────────
  const prevEmpty = !row.previousAnnualGross.trim()
  const currEmpty = !row.currentAnnualGross.trim()
  if (prevEmpty) {
    findings.push(err('V-05', row.excelRow, 'Previous Annual Gross', 'Previous Annual Gross is required.'))
  }
  if (currEmpty) {
    findings.push(err('V-05', row.excelRow, 'Current Annual Gross', 'Current Annual Gross is required.'))
  }

  const previousGross = prevEmpty ? null : parseSalary(row.previousAnnualGross)
  const currentGross = currEmpty ? null : parseSalary(row.currentAnnualGross)

  if (!prevEmpty && previousGross === null) {
    findings.push(err('V-07', row.excelRow, 'Previous Annual Gross', `Previous Annual Gross "${row.previousAnnualGross.trim()}" is not a valid amount.`))
  }
  if (!currEmpty && currentGross === null) {
    findings.push(err('V-07', row.excelRow, 'Current Annual Gross', `Current Annual Gross "${row.currentAnnualGross.trim()}" is not a valid amount.`))
  }

  // ── V-08 — current must exceed previous ───────────────────────
  if (previousGross !== null && currentGross !== null && currentGross <= previousGross) {
    findings.push(err('V-08', row.excelRow, 'Current Annual Gross',
      `Current Annual Gross ${currentGross.toFixed(2)} is not greater than Previous Annual Gross ${previousGross.toFixed(2)}. A salary increase letter needs a higher current figure.`))
  }

  // ── V-09 — annual remuneration cross-check ────────────────────
  let annualRemuneration: number | null = null
  if (row.annualRemuneration.trim()) {
    annualRemuneration = parseSalary(row.annualRemuneration)
    if (annualRemuneration !== null && currentGross !== null && annualRemuneration !== currentGross) {
      findings.push(warn('V-09', row.excelRow, 'Annual Remuneration',
        `Annual Remuneration ${annualRemuneration.toFixed(2)} does not equal Current Annual Gross ${currentGross.toFixed(2)}.`))
    }
  }

  // ── V-10 — amount-in-words matches the figure ─────────────────
  let previousWords: string | null = null
  let currentWords: string | null = null

  if (previousGross !== null) {
    const generated = nairaToWords(previousGross)
    if (!row.previousAmountInWords.trim()) {
      wordsAutoGenerated.previous = true
      previousWords = generated
    } else if (!amountWordsEqual(row.previousAmountInWords, generated)) {
      findings.push(err('V-10', row.excelRow, 'Previous Amount in word',
        `Words "${row.previousAmountInWords.trim()}" do not match the figure ${previousGross.toFixed(2)}. Expected: ${generated}.`))
      previousWords = generated
    } else {
      previousWords = generated
    }
  }

  if (currentGross !== null) {
    const generated = nairaToWords(currentGross)
    if (!row.currentAmountInWords.trim()) {
      wordsAutoGenerated.current = true
      currentWords = generated
    } else if (!amountWordsEqual(row.currentAmountInWords, generated)) {
      findings.push(err('V-10', row.excelRow, 'Current Amount in word',
        `Words "${row.currentAmountInWords.trim()}" do not match the figure ${currentGross.toFixed(2)}. Expected: ${generated}.`))
      currentWords = generated
    } else {
      currentWords = generated
    }
  }

  // ── V-11 — mail validity ──────────────────────────────────────
  if (row.mail.trim() && !EMAIL_RE.test(row.mail.trim())) {
    findings.push(warn('V-11', row.excelRow, 'Mail', `Mail "${row.mail.trim()}" is not a valid email address.`))
  }

  // ── V-14 — per-row override dates (if present) ─────────────────
  if (row.overrides.letterDate && !parseDate(row.overrides.letterDate)) {
    findings.push(err('V-14', row.excelRow, 'Letter Date', `Letter Date override "${row.overrides.letterDate}" is not a valid date.`))
  }
  if (row.overrides.effectiveDate && !parseDate(row.overrides.effectiveDate)) {
    findings.push(err('V-14', row.excelRow, 'Effective Date', `Effective Date override "${row.overrides.effectiveDate}" is not a valid date.`))
  }
  if (row.overrides.performanceYear && !isValidPerformanceYear(row.overrides.performanceYear)) {
    findings.push(err('V-14', row.excelRow, 'Performance Year', `Performance Year override "${row.overrides.performanceYear}" must be a four-digit year.`))
  }

  return {
    findings,
    previousGross,
    currentGross,
    annualRemuneration,
    previousWords,
    currentWords,
    wordsAutoGenerated,
  }
}
