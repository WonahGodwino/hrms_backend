const norm = (v: unknown) =>
  String(v && typeof v === 'object' && 'text' in (v as any) ? (v as any).text : v ?? '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')

/**
 * Finds the header row of a sheet that may carry a title banner above it.
 * `anchors` are normalised header names (letters/digits only, lower case); the
 * first row within `maxScan` rows containing every anchor wins. Falls back to
 * row 1 so unbannered legacy files keep working.
 */
export function findHeaderRow(ws: ExcelJS.Worksheet, anchors: string[], maxScan = 12): number {
  const want = anchors.map(norm)
  const limit = Math.min(maxScan, ws.rowCount);
  for (let r = 1; r <= limit; r++) {
    const values = (ws.getRow(r).values as unknown[]) || []
    const have = new Set(values.map(norm))
    if (want.every((a) => have.has(a))) return r
  }
  return 1
}

/**
 * Separate "Instructions" sheet for upload templates. Notes never go under the data of a
 * template: users add their own rows there, and merged note cells would get in the way.
 */
export function addInstructionsSheet(
  wb: ExcelJS.Workbook,
  opts: { title?: string; subtitle?: string; sections: { heading: string; lines: string[] }[] }
) {
  const ws = wb.addWorksheet('Instructions', { views: [{ showGridLines: false }] })
  const colCount = 8
  ws.columns = Array.from({ length: colCount }, () => ({ width: 16 }))
  let r = addTitleBand(ws, { title: opts.title || 'Instructions', subtitle: opts.subtitle, colCount })
  for (const section of opts.sections) {
    r = addNotes(ws, r, colCount, section.heading, section.lines) + 1
  }
  return ws
}
