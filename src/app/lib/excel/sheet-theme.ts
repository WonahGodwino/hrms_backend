// src/app/lib/excel/sheet-theme.ts
//
// Shared look for every generated .xlsx outside PHED, based on the Attendance
// export: brand-purple palette, a centred two-line title band (title, then a
// "Company | range | Generated ..." line), banded rows, a frozen header and a
// confidential footer. Tables are written with their header on row 4, so any
// parser reading a sheet made by writeStyledTable must locate the header row
// with findHeaderRow() instead of assuming row 1.
import type ExcelJS from 'exceljs'

export const XL = {
  BRAND: '6C5DD3',
  BRAND_DEEP: '5843BE',
  INK: '1B1B2F',
  MUTED: '92929D',
  TINT: 'EFECFB',
  ZEBRA: 'FAFBFF',
  HAIRLINE: 'E7E8F1',
  SUCCESS_BG: 'E8F7EE',
  SUCCESS_FG: '0F7A37',
  WARN_BG: 'FBF0DC',
  WARN_FG: 'A35C00',
  DANGER_BG: 'FCEAEB',
  DANGER_FG: 'C92A30',
  INFO_BG: 'E5F0FC',
  INFO_FG: '1456B0',
} as const

export const XLSX_MIME = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'

export const solid = (hex: string): ExcelJS.Fill => ({ type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${hex}` } })
export const argb = (hex: string) => ({ argb: `FF${hex}` })

export function generatedLabel(d: Date = new Date()): string {
  return d.toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
    timeZone: 'Africa/Lagos',
  })
}

/** "Company | extra | Generated 03 Oct 2026, 12:00" */
export function buildSubtitle(parts: (string | undefined | null | false)[], generatedAt?: Date): string {
  return [...parts.filter(Boolean), `Generated ${generatedLabel(generatedAt)}`].join('   |   ')
}

export function confidentialFooter(companyName?: string | null): string {
  return companyName
    ? `This document is generated by ${companyName}, it is confidential and intended for authorized use only.`
    : 'This document is confidential and intended for authorized use only.'
}

/** Strip characters that are illegal in file names but keep spaces and parentheses. */
export function safeFileName(name: string): string {
  return name.replace(/[\\/:*?"<>|]+/g, '').replace(/\s+/g, ' ').trim()
}

/** Content-Disposition value that survives non-ASCII names. */
export function attachmentDisposition(fileName: string): string {
  const ascii = fileName.replace(/[^\x20-\x7E]/g, '-')
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(fileName)}`
}

/** The banner, notes and footer always span every column of the table. */
export const bannerSpan = (colCount: number) => Math.max(colCount, 2)

/** Centred two-line title band across `colCount` columns. Returns the next free row (4). */
export function addTitleBand(ws: ExcelJS.Worksheet, opts: { title: string; subtitle?: string; colCount: number }): number {
  const { title, subtitle, colCount } = opts
  const span = bannerSpan(colCount)

  ws.mergeCells(1, 1, 1, span)
  const t = ws.getCell(1, 1)
  t.value = title
  t.font = { bold: true, size: 16, color: argb('FFFFFF') }
  t.fill = solid(XL.BRAND)
  t.alignment = { horizontal: 'center', vertical: 'middle' }
  ws.getRow(1).height = 34

  ws.mergeCells(2, 1, 2, span)
  const s = ws.getCell(2, 1)
  s.value = subtitle || ''
  s.font = { size: 10, color: argb(XL.INK) }
  s.fill = solid(XL.TINT)
  s.alignment = { horizontal: 'center', vertical: 'middle' }
  ws.getRow(2).height = 22

  ws.getRow(3).height = 8
  return 4
}

export type XlAlign = 'left' | 'center' | 'right'

export interface XlColumn {
  header: string
  key: string
  width?: number
  align?: XlAlign
  numFmt?: string
}

export function styleHeaderRow(row: ExcelJS.Row, columns: XlColumn[]) {
  columns.forEach((c, i) => {
    const cell = row.getCell(i + 1)
    cell.value = c.header
    cell.font = { bold: true, size: 10, color: argb('FFFFFF') }
    cell.fill = solid(XL.BRAND_DEEP)
    cell.alignment = { horizontal: c.align || 'left', vertical: 'middle', wrapText: true }
    cell.border = { bottom: { style: 'thin', color: argb(XL.BRAND) } }
  })
  row.height = 24
}

export function styleBodyRow(row: ExcelJS.Row, index: number, columns: XlColumn[]) {
  columns.forEach((c, i) => {
    const cell = row.getCell(i + 1)
    if (!cell.fill || (cell.fill as any).pattern !== 'solid') cell.fill = solid(index % 2 === 1 ? XL.ZEBRA : 'FFFFFF')
    cell.font = { size: 10, color: argb(XL.INK), ...(cell.font || {}) }
    cell.alignment = { horizontal: c.align || 'left', vertical: 'middle', ...(cell.alignment || {}) }
    cell.border = { bottom: { style: 'thin', color: argb(XL.HAIRLINE) } }
    if (c.numFmt) cell.numFmt = c.numFmt
  })
  row.height = 20
}

export function addNotes(ws: ExcelJS.Worksheet, startRow: number, colCount: number, heading: string, lines: string[]): number {
  let r = startRow
  const span = bannerSpan(colCount)
  ws.mergeCells(r, 1, r, span)
  const h = ws.getCell(r, 1)
  h.value = heading
  h.font = { bold: true, size: 11, color: argb(XL.BRAND_DEEP) }
  h.border = { bottom: { style: 'medium', color: argb(XL.BRAND) } }
  h.alignment = { vertical: 'middle' }
  ws.getRow(r).height = 22
  r += 1
  for (const line of lines) {
    ws.mergeCells(r, 1, r, span)
    const c = ws.getCell(r, 1)
    c.value = line
    c.font = { size: 10, color: argb(XL.INK) }
    c.alignment = { vertical: 'middle', wrapText: true, indent: 1 }
    r += 1
  }
  return r
}

export function addFooter(ws: ExcelJS.Worksheet, row: number, colCount: number, text: string) {
  ws.mergeCells(row, 1, row, bannerSpan(colCount))
  const f = ws.getCell(row, 1)
  f.value = text
  f.font = { italic: true, size: 8, color: argb(XL.MUTED) }
  f.alignment = { horizontal: 'center', vertical: 'middle' }
}

export interface StyledTableOptions {
  title: string
  subtitle?: string
  columns: XlColumn[]
  rows: Record<string, any>[]
  notes?: { heading?: string; lines: string[] }
  footer?: string
  autoFilter?: boolean
  emptyMessage?: string
  /** Called after a data row is written and styled, for per-row colouring. */
  onRow?: (row: ExcelJS.Row, data: Record<string, any>, index: number) => void
}

/**
 * Writes banner + header + banded rows + notes + footer. The header is always on
 * `headerRow` (4), data starts on `firstDataRow` (5).
 */
export function writeStyledTable(ws: ExcelJS.Worksheet, opts: StyledTableOptions) {
  const { columns, rows } = opts
  const colCount = columns.length
  ws.columns = columns.map((c) => ({ key: c.key, width: c.width || 18 }))
  ws.views = [{ state: 'frozen', ySplit: 4, showGridLines: false }]

  const headerRow = addTitleBand(ws, { title: opts.title, subtitle: opts.subtitle, colCount })
  styleHeaderRow(ws.getRow(headerRow), columns)

  rows.forEach((data, i) => {
    const row = ws.getRow(headerRow + 1 + i)
    columns.forEach((c, ci) => {
      const v = data[c.key]
      row.getCell(ci + 1).value = v === undefined ? null : v
    })
    styleBodyRow(row, i, columns)
    opts.onRow?.(row, data, i)
  })

  let next = headerRow + 1 + rows.length
  if (rows.length === 0 && opts.emptyMessage) {
    ws.mergeCells(next, 1, next, bannerSpan(colCount))
    const c = ws.getCell(next, 1)
    c.value = opts.emptyMessage
    c.font = { italic: true, size: 10, color: argb(XL.MUTED) }
    c.alignment = { horizontal: 'center', vertical: 'middle' }
    ws.getRow(next).height = 28
    next += 1
  } else if (rows.length > 0 && opts.autoFilter !== false) {
    ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow + rows.length, column: colCount } }
  }

  next += 1
  if (opts.notes && opts.notes.lines.length > 0) {
    next = addNotes(ws, next, colCount, opts.notes.heading || 'Notes', opts.notes.lines) + 1
  }
  if (opts.footer) addFooter(ws, next, colCount, opts.footer)

  ws.pageSetup = { orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0, printTitlesRow: `${headerRow}:${headerRow}` }
  return { headerRow, firstDataRow: headerRow + 1, lastDataRow: headerRow + rows.length }
}

/** Colour a status-like cell (Present, Failed, Active ...). */
export function toneCell(cell: ExcelJS.Cell, tone: 'success' | 'warn' | 'danger' | 'info') {
  const map = {
    success: [XL.SUCCESS_BG, XL.SUCCESS_FG],
    warn: [XL.WARN_BG, XL.WARN_FG],
    danger: [XL.DANGER_BG, XL.DANGER_FG],
    info: [XL.INFO_BG, XL.INFO_FG],
  } as const
  const [bg, fg] = map[tone]
  cell.fill = solid(bg)
  cell.font = { bold: true, size: 10, color: argb(fg) }
}

